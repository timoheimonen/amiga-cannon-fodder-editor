"""Assemble the editor and the WHDLoad slave and embed them in patch.py.

Usage: python3 build.py [--vasm PATH] [--vlink PATH]

Requires the vasm 68000 assembler with Motorola syntax (vasmm68k_mot) and the
vlink linker. No game file is read: the patch table records only where the
editor changes the game's main program, the SHA-256 of the bytes it expects
there and the bytes it writes. Only the section of patch.py between the
"GENERATED BY build.py" markers is written again, so users of patch.py need
only Python 3.

The editor has three parts:
- the resident (src/editor/resident/bootstrap.s), which patch.py appends to
  the game's main program, with four small bodies that replace game code in
  place (hill_body, campaign_body, base_attributes, resource_loaders);
- seventeen overlay modules (src/editor/modules), which the slave loads from
  the install's Custom directory into one shared bank when they are needed;
- the hooks (src/hooks.json), the jumps from the game's code into the editor
  and the slave's host patches.
The slave (src/whdload/slave.s) is assembled with the size of the patched
main program.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import json
from pathlib import Path
import re
import struct
import subprocess
import tempfile
import textwrap
import zlib

ROOT = Path(__file__).resolve().parent
EDITOR = ROOT / 'src/editor'
WHDLOAD = ROOT / 'src/whdload'
INCLUDE = EDITOR / 'include'
HOOKS = ROOT / 'src/hooks.json'
PATCH = ROOT / 'patch.py'
VERSION = '1.1'
HEADER = f'Cannon Fodder In-Game Level Editor V{VERSION}'
BEGIN = '# BEGIN GENERATED BY build.py - do not edit by hand\n'
END = '# END GENERATED BY build.py\n'

